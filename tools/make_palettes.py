"""Writes src/views/PaletteData.inc: the colour palettes the studio ships, taken
from the reference implementations rather than typed in.

    python tools/make_palettes.py <Rscript>

ggplot2's default hue palette and its ColorBrewer palettes come from R
(scales::hue_pal(), RColorBrewer::brewer.pal()), the viridis family from
viridisLite, and matplotlib's qualitative cycles from matplotlib itself.
Rerun it to update them; the licences are in LICENSING.md.
"""

import subprocess
import sys

import matplotlib
from matplotlib import colors as mcolors

RSCRIPT = sys.argv[1]
OUT = "src/views/PaletteData.inc"


def r(expr):
    out = subprocess.run([RSCRIPT, "-e", f"cat({expr}, sep = ' ')"], capture_output=True, text=True, check=True)
    return out.stdout.split()


def hexes(colours):
    return ", ".join(f'"{c[:7].upper()}"' for c in colours)


lines = ["// SPDX-License-Identifier: BSD-3-Clause", "// Copyright (c) 2026 Franz X. Mohr", "",
         "// Generated by tools/make_palettes.py -- do not edit.", ""]

# ggplot2: the hue palette depends on the number of series.
lines.append("// ggplot2 (scales::hue_pal()), one row per number of series, 1 to 12.")
lines.append("static const std::vector<std::vector<const char *>> kGgplotHue = {")
for n in range(1, 13):
    lines.append(f"    {{{hexes(r(f'scales::hue_pal()({n})'))}}},")
lines.append("};")
lines.append("")

brewer = {"Set1": 9, "Set2": 8, "Dark2": 8, "Paired": 12}
lines.append("// ColorBrewer (RColorBrewer::brewer.pal()), Apache License 2.0, Cynthia A. Brewer.")
for name, n in brewer.items():
    lines.append(f"static const std::vector<const char *> kBrewer{name} = {{{hexes(r(f'RColorBrewer::brewer.pal({n}, \"{name}\")'))}}};")
lines.append("")

lines.append("// matplotlib's qualitative cycles.")
for name in ["tab10", "tab20", "tab20b", "tab20c", "petroff10"]:
    if name in matplotlib.colormaps:
        cols = [mcolors.to_hex(c) for c in matplotlib.colormaps[name].colors]
    else:
        # The accessible cycle of Petroff (2021) is a style sheet's colour cycle.
        import matplotlib.style
        cycle = matplotlib.style.library[name]["axes.prop_cycle"]
        cols = [mcolors.to_hex(c["color"]) for c in cycle]
    lines.append(f"static const std::vector<const char *> kMpl{name.capitalize()} = {{{hexes(cols)}}};")
lines.append("")

lines.append("// The viridis family (viridisLite), 64 evenly spaced stops each.")
for option, name in [("D", "Viridis"), ("A", "Magma"), ("B", "Inferno"), ("C", "Plasma"), ("E", "Cividis")]:
    lines.append(f"static const std::vector<const char *> k{name} = {{{hexes(r(f'viridisLite::viridis(64, option = \"{option}\")'))}}};")
lines.append("")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", OUT)
